export const TYPE_CODES = Object.keys(TYPES)

/**
 * Собирает трёхбуквенный код из ответов квиза.
 *
 * У рационалов (J) первой в коде идёт судящая функция, у иррационалов (P) —
 * воспринимающая; третья буква — вертность. Именно это правило даёт
 * канонические коды: LSE, ILI, SEE и так далее.
 */
export function typeFromAnswers(answers: Answers): string {
  const extraverted = answers[0] === 'A'
  const logical = answers[1] === 'A'
  const sensing = answers[2] === 'A'
  const rational = answers[3] === 'A'

  const judging = logical ? 'L' : 'E'
  const perceiving = sensing ? 'S' : 'I'
  const attitude = extraverted ? 'E' : 'I'

  return rational
    ? `${judging}${perceiving}${attitude}`
    : `${perceiving}${judging}${attitude}`
}

export function getType(code: string): SocionicsType | null {
  return TYPES[code] ?? null
}

/**
 * Позиция на каждой из четырёх осей в процентах (0 — левый полюс, 100 — правый).
 *
 * Ответ даёт не абсолютный полюс, а выраженную склонность: 18% / 82% читается
 * честнее, чем край шкалы, и точнее отражает смысл короткого теста.
 */
export function axisPositions(answers: Answers): number[] {
  return answers.map((answer) => (answer === 'A' ? 18 : 82))
}

export type StoredData = {
  answers: Answers
  type: string
  email: string
}

export const STORAGE_KEY = 'socionics_data'

export function isAnswers(value: unknown): value is Answers {
  return (
    Array.isArray(value) &&
    value.length === 4 &&
    value.every((item) => item === 'A' || item === 'B')
  )
}

export function isStoredData(value: unknown): value is StoredData {
  if (typeof value !== 'object' || value === null) return false
  const data = value as Record<string, unknown>
  return (
    isAnswers(data.answers) &&
    typeof data.type === 'string' &&
    data.type in TYPES &&
    typeof data.email === 'string'
  )
}

