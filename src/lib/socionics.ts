/**
 * Соционическая типология: 16 типов, выводимых из 4 дихотомий.
 *
 * Ответы квиза кодируются как "A" | "B" и раскладываются по осям:
 *   answers[0]  A = экстраверт (E)      B = интроверт (I)
 *   answers[1]  A = логика     (L)      B = этика     (F)
 *   answers[2]  A = сенсорика  (S)      B = интуиция  (N)
 *   answers[3]  A = рациональность (J)  B = иррациональность (P)
 *
 * Трёхбуквенный код собирается по каноническому правилу соционики:
 * у рационалов первой идёт судящая функция, у иррационалов — воспринимающая,
 * третьей буквой всегда идёт вертность (E/I).
 */

